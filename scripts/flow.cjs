const { chromium } = require('@playwright/test');
(async () => {
  const browser = await chromium.launch({ headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, deviceScaleFactor: 1 });
  const errors = [];
  page.on('console', (msg) => { if (msg.type() === 'error') errors.push(msg.text()); });
  page.on('pageerror', (err) => errors.push('PAGEERROR: ' + err.message));
  await page.goto('http://127.0.0.1:5173', { waitUntil: 'networkidle' });
  await page.evaluate(() => localStorage.clear());
  await page.reload({ waitUntil: 'networkidle' });
  await page.getByRole('button', { name: /Build my hero pool/i }).click();
  await page.waitForTimeout(400);
  await page.screenshot({ path: 'shots/01-rank.png', fullPage: true });
  await page.getByRole('button', { name: /Build hero pools/i }).click();
  await page.waitForTimeout(400);
  await page.screenshot({ path: 'shots/02-pool-empty.png', fullPage: true });
  await page.getByRole('button', { name: /Auto-fill all lanes/i }).click();
  await page.waitForTimeout(600);
  await page.screenshot({ path: 'shots/03-pool-filled.png', fullPage: true });
  await page.getByRole('button', { name: /Review profile/i }).click();
  await page.waitForTimeout(400);
  await page.screenshot({ path: 'shots/04-review.png', fullPage: true });
  await page.getByRole('button', { name: /Save & enter match setup/i }).click();
  await page.waitForTimeout(700);
  await page.screenshot({ path: 'shots/05-setup.png', fullPage: true });
  await page.getByRole('button', { name: /Mid Lane/i }).first().click();
  await page.waitForTimeout(300);
  await page.screenshot({ path: 'shots/06-setup-selected.png', fullPage: true });
  await page.getByRole('button', { name: /Let’s play rank/i }).click();
  await page.waitForTimeout(500);
  await page.screenshot({ path: 'shots/07-ban.png', fullPage: true });
  const smartBan = page.locator('.smart-ban__action').first();
  if (await smartBan.isVisible()) await smartBan.click();
  await page.waitForTimeout(300);
  await page.getByRole('button', { name: /Enter live draft/i }).click();
  await page.waitForTimeout(500);
  await page.screenshot({ path: 'shots/08-draft.png', fullPage: true });
  // Add an enemy pick
  const enemyEmpty = page.locator('.draft-team--enemy .pick-row--empty').first();
  await enemyEmpty.click();
  await page.waitForTimeout(300);
  await page.locator('.picker__search input').fill('fanny');
  await page.waitForTimeout(300);
  await page.screenshot({ path: 'shots/09-picker.png' });
  await page.keyboard.press('Enter');
  await page.waitForTimeout(500);
  await page.screenshot({ path: 'shots/10-draft-enemy.png', fullPage: true });
  await page.getByRole('button', { name: /^It’s my turn$/ }).first().click();
  await page.waitForTimeout(900);
  await page.screenshot({ path: 'shots/11-turn-scan.png' });
  await page.getByRole('button', { name: /Reveal now/i }).click();
  await page.waitForTimeout(500);
  await page.screenshot({ path: 'shots/12-turn-results.png' });
  await page.getByRole('button', { name: /Lock & transfer/i }).first().click();
  await page.waitForTimeout(700);
  await page.screenshot({ path: 'shots/13-draft-locked.png', fullPage: true });
  await page.getByRole('button', { name: /The game will start/i }).first().click();
  await page.waitForTimeout(500);
  await page.screenshot({ path: 'shots/14-strategy.png', fullPage: true });
  console.log('ERRORS:', JSON.stringify(errors, null, 2));
  console.log('FINAL URL:', page.url());
  console.log('FINAL TEXT:', (await page.locator('body').innerText()).slice(0, 1600));
  await browser.close();
})();
