const { chromium } = require('@playwright/test');
(async () => {
  const browser = await chromium.launch({ headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  await page.goto('http://127.0.0.1:5173', { waitUntil: 'networkidle' });
  await page.evaluate(() => localStorage.clear());
  await page.reload({ waitUntil: 'networkidle' });
  await page.getByRole('button', { name: /Build my hero pool/i }).click();
  await page.getByRole('button', { name: /Build hero pools/i }).click();
  await page.getByRole('button', { name: /Auto-fill all lanes/i }).click();
  await page.waitForTimeout(800);
  console.log('FOOTER:', await page.locator('.onboarding-footer__status span').first().innerText());
  console.log('TABS:', await page.locator('.lane-tab').allInnerTexts());
  console.log('TOAST:', await page.locator('.toast__body').allInnerTexts());
  console.log('SLOTS:', await page.locator('.pool-slot').count());
  await page.getByRole('button', { name: /Review profile/i }).click();
  await page.waitForTimeout(300);
  console.log('REVIEW COUNTS:', await page.locator('.review-lane__head').allInnerTexts());
  console.log('SUMMARY:', await page.locator('.review-summary__big').innerText());
  console.log('ROWS:', await page.locator('.review-summary__rows > div').allInnerTexts());
  await browser.close();
})();
